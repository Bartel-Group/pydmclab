class AnalyzePhonons(object):
    def __init__(self, unitcell: str|dict,
                 force_data: np.ndarray|list, 
                 primitive_matrix: list|str = "auto",
                 symprec=1e-5,
                 mesh: int|list|float=[30, 30, 30],
                 dataset: dict = None,
                 E0: float = 0,
                 init_kwargs: dict ={}
):
        """
        Class to analyze phonon data from a VASP calculation using Phonopy, Can return force constants, dynamical matrix, mesh data, thermal properties, band structure, and total density of states.
        Args:
            unitcell (str or dict):
                Path to the unitcell structure file (e.g., POSCAR) or structure as dict.
            force_data (array-like or list):
                List of forces from a set of displaced structures calculations. Shape=(N, natoms, 3) where N is the number of displacements and natoms is the number of atoms in the supercell.
                OR list of force constants. Shape=(natoms, natoms, 3, 3).
                WARNING: If you are using a dataset generated by phonopy.displacements, make sure the force_data is listing the forces from the displaced structures in the same order as the dataset.
            primitive_matrix (list):
                Transformation matrix from the unitcell to the primitive cell. e.g. [[0.5, 0, 0], [0, 0.5, 0], [0, 0, 1]] would reduce a 2x2x1 supercell to 1x1x1.
                Default is "auto", which will automatically reduce the results to the primitive cell.
                Set explicitly if want the results in terms of a different unitcell
            mesh (array-like or float):
                Mesh numbers along a, b, c axes when array_like object is given, shape=(3,).
                When float value is given, uniform mesh is generated following VASP convention by N = max(1, nint(l * |a|^*)) where 'nint' is the function to return the nearest integer. In this case, it is forced to set is_gamma_center=True.
                Default value is 100.0.
            dataset (dict):
                Only for Finite Displacement. Dictionary containing displacement information, can optionally include forces and supercell energy. But these can also be provided separately in force_data, this easier because you can just feed it as a list of arrays.
                Usually generated using phonopy's phonopy.displacements and then extract dataset using phonopy.dataset
                Helper function get_displacements_for_phonons() in hpc_worflows/phonon_calcs generates this for you as well.
                WARNING: See warning for force_data argument.
                Type 1. One atomic displacement in each supercell:
                {'natom': number of atoms in supercell,
                 'first_atoms': [
                   {'number': atom index of displaced atom,
                    'displacement': displacement in Cartesian coordinates,
                    'forces'(optional): forces on atoms in supercell,
                    'supercell_energy'(optional): energy of supercell},
                   {...}, ...]}
                There is a type 2 dataset for multiple displacements in each supercell, but this is not implemented here. Might look into it in the future if needed.
            E0 (float):
                In eV/atom.
                Optional static 0 K energy of the supercell. This is added to the phonon free energy to get the total free energy.
                If E0 is not provided, the Helmholtz free energy will only include the phonon contribution.
            init_kwargs:
                See https://github.com/phonopy/phonopy/blob/main/phonopy/api_phonopy.py for other init kwargs available
        """

        self.unitcell = StrucTools(unitcell).structure_as_dict
        self.force_data = force_data
        self.primitive_matrix = primitive_matrix
        self.dataset = dataset
        self.symprec = symprec
        self.E0 = E0

        if isinstance(mesh, (list, tuple)) and len(mesh) != 3:
            raise ValueError(
                "Mesh should be a list of three integers or an int."
            )

        self.pymatgen_struc = StrucTools(unitcell).structure
        self.natoms_unitcell = self.pymatgen_struc.num_sites 
        natoms_unitcell = self.natoms_unitcell 

        unitcell = get_phonopy_structure(self.pymatgen_struc) #PhonopyAtoms structure object

        phonon = Phonopy(unitcell=unitcell, primitive_matrix=primitive_matrix, symprec=symprec, **init_kwargs) 
        self.natoms = len(phonon.primitive) #natoms in primitive cell. results reported from phonopy are corresponding to number of atoms in the primitive. If you force it to not do a transformation to the primitive then phonon.primitive will correspond to whatever transformation you specified (whether it be the unitcell or another cell)
        phonon.dataset = dataset

        if force_data:
            arr = np.array(force_data)
            if arr.ndim == 3 and arr.shape[1:] == (natoms_unitcell, 3):
                # Looks like forces from displacements
                print(f"Detected forces from {arr.shape[0]} displacement calculations")
                self.forces = arr
                phonon.forces = arr 
                if phonon.dataset is None:
                    raise ValueError("Unable to set dataset for phonon calculation. Please provide a valid dataset or force constants.")
                phonon.produce_force_constants()
                self.force_constants = phonon.force_constants

            elif arr.shape == (natoms_unitcell, natoms_unitcell, 3, 3):
                # Looks like force constants
                print(f"Detected force constants in full form")
                phonon.force_constants = arr
                self.force_constants = phonon.force_constants
            else:
                raise ValueError(
                    f"Unrecognized force_data shape: {arr.shape}\n"
                    f"Expected one of:\n"
                    f"  - Forces: (N_displacements, {natoms_unitcell}, 3)\n"
                    f"  - Force constants: ({natoms_unitcell}, {natoms_unitcell}, 3, 3)\n"
                    f"\nBased on supercell with {natoms_unitcell} atoms"
                )

            # self.dynamical_matrix = phonon.dynamical_matrix # This is just a phonopy.dynamical_matrix.DynamicalMatrix object. Need it to run mesh.
            _mesh_out = phonon.run_mesh(mesh) #Need to run this in order to run everything else downstream

            self.phonon = phonon

        self._band_structure = None
        self._band_structure_paths = None

    @property
    def mesh_dict(self):
        """
        Returns the mesh data for the phonon object in a dictionary
        """
        mesh_dict = self.phonon.get_mesh_dict()
        return mesh_dict
    
    @property
    def find_high_symmetry_path(self):
        '''
        Find the high symmetry qpoints and corresponding coordinates for the given structure using seekpath.
        Returns:
                {
                ('Γ', 'X'): [[0.0, 0.0, 0.0], [0.5, 0.0, 0.0]],
                ('X', 'S'): [[0.5, 0.0, 0.0], [0.5, 0.5, 0.0]], ...
                }
        '''
        import seekpath
        structure = self.pymatgen_struc
        structure_tuple = (
            structure.lattice.matrix,
            structure.frac_coords,
            structure.atomic_numbers
        )
        path_data = seekpath.get_path(structure_tuple)
        path = path_data['path']
        
        out = {tuple(point.replace('GAMMA', 'Γ') for point in p): 
            [path_data['point_coords'][p[0]], path_data['point_coords'][p[1]]] 
            for p in path}
        
        return out

    def band_structure(
        self,
        paths: list|dict|None = None,
        Nq: int = 100
    ):
        """
        Returns the band structure for the phonon object in a dictionary
        Args:
            paths (list or dict or None):
                If None is provided, a path will automatically be found using seekpath
                List of paths in reciprocal space. e.g.: 
                            [
                                [[0.0, 0.0, 0.0], [0.5, 0.5, 0.0]],  # Γ to X 
                                [[0.5, 0.5, 1.0], [0, 0, 0]],  # X to K to Γ
                                [[0.0, 0.0, 0.0], [0.5, 0.5, 0.5]],  # Γ to L
                            ] (these coordinates/high symmetry points vary structure to structure)
                Or dictionary of paths with labels. e.g.:
                            {'Γ-X': [[0.0, 0.0, 0.0], [0.5, 0.5, 0.0]],
                            'X-Γ': [[0.5, 0.5, 1.0], [0, 0, 0]],...}
                            This will save the labels in the band structure dictionary for ease of plotting.

        Returns:
            {'qpoints': arrays of q points, 'distances': arrays of distances, 'frequencies': arrays of frequencies, 'eigenvectors': arrays of eigenvectors, group_velocities': arrays of group velocities, 'paths': list of path labels if provided or automatically found}
        """

        path_data = None
        if paths==None:
            path_data = self.find_high_symmetry_path
            paths = [path_data[key] for key in path_data]
        elif isinstance(paths, dict):
            path_data = paths
            paths = list(paths.values())

        def get_band(q_start, q_stop, N):
            """ Return path between q_start and q_stop """
            return np.array([q_start + (q_stop-q_start)*i/(N-1) for i in range(N)])

        bands = []
        for path in paths:
            qpoints = get_band(np.array(path[0]), np.array(path[1]), Nq)
            bands.append(qpoints)

        bands_equal = (
            len(self._band_structure_paths) == len(bands)
            and all(np.array_equal(a1, a2) for a1, a2 in zip(self._band_structure_paths, bands))
        ) if self._band_structure_paths else False

        if not bands_equal:
            print("Calculating band structure...")
            _ = self.phonon.run_band_structure(bands)
            self._band_structure_paths = bands        
            self._band_structure = self.phonon.get_band_structure_dict()
            if path_data is not None:
                self._band_structure['path'] = list(path_data.keys())

            h = physical_constants['Planck constant in eV/Hz'][0]
            # hbar = h / (2 * np.pi)
            freq_points = np.array(self._band_structure['frequencies'])
            #convert frequencies from THz to eV
            freq_points_ev = freq_points * 1e12 * h #I think it is not necessary to divide by 2pi here because phonopy already gives frequencies in Hz, not angular frequencies
            self._band_structure['frequencies'] = convert_numpy_to_native(freq_points_ev)

        return self._band_structure

    @property
    def total_dos(self):
        """
        Returns the total density of states for the phonon object in a dictionary.
        The units are converted from phonopy's default THz to eV!!
        Returns:
            {'E0' : 0 K internal energy (eV/atom),
            'total_dos' :
            [{'E' : energy level (eV), 'total_dos': total density of states}, ...],
            'units': {'frequency': 'eV', 'dos': 'states/eV', 'energy': 'eV/atom'}
            }
        """
        if not hasattr(self, '_total_dos'):
            print("Calculating total density of states...")
            _ = self.phonon.run_total_dos()
            total_dos = self.phonon.get_total_dos_dict()
            h = physical_constants['Planck constant in eV/Hz'][0]
            tdos = total_dos['total_dos']/(h*1e12) # This is to normalize the DOS to 1/eV (phonopy default is 1/THz)
            freq_points = total_dos['frequency_points']
            freq_points_ev = freq_points * 1e12 * h #convert frequencies from THz to eV
            self._total_dos = {
                'E0': self.E0,
                'total_dos': [{'E': E, 'total_dos': dos} for E, dos in zip(freq_points_ev, tdos)],
                'units': {'frequency': 'eV', 'dos': 'states/eV', 'energy': 'eV/atom'}
            }

        return self._total_dos

    def thermal_properties(self, temperatures=np.linspace(0, 2000, 101), 
                  include_heat_capacity: bool = True, 
                  move_imaginary: bool = False):
        """
        Helmholtz free energy calculated using ASE's CrystalThermo module.
        Args:
            temperatures (array-like):
                Array of temperatures in Kelvin at which to calculate the Helmholtz free energy.
            include_heat_capacity (bool):
                If True, includes heat capacity in the output.
            move_imaginary (bool):
                If True, moves imaginary frequencies to their absolute values.
                If False, removes imaginary frequencies from the DOS.
                In order to calculate thermodynamic properties, the phonon DOS must not contain imaginary frequencies, so it will always be cleaned.
        Returns:
            [{'T': 300, 
            'F': float,
            'S': float,
            'Cv': float}, ...]
            Units are eV/atom
        """
        phonon_dos = self.total_dos
        phonon_dos['E0'] = self.E0*self.natoms #Convert to eV/supercell for CrystalThermo
        normalize=self.natoms
        helmholtz = Helmholtz(phonon_dos=phonon_dos, temperatures=temperatures, normalize=normalize, move_imaginary=move_imaginary) #this will normalize to eV/atom not eV/formula unit
        F = helmholtz.helmholtz()
        if include_heat_capacity: 
            Cv = helmholtz.heat_capacity()
            for i in range(len(F['thermal_properties'])):
                F['thermal_properties'][i]['Cv'] = Cv['thermal_properties'][i]['Cv']
        return F

    def phonopy_thermal_properties(
        self,
        phonopy_tprops_kwargs=None,
        force_rerun: bool = False,
    ):
        """
        returns the thermal properties for the phonon object in a dictionary
        Args:
            phonopy_tprops_kwargs (dict, optional)
                see Phonopy.run_thermal_properties() for possible kwargs and defaults
            force_rerun (bool, optional)
                If you already ran thermal properties but now want to change some of the arguments
                and want it to recalculate the thermal properties, set this to True. Default is False.

        Returns parsed thermal properties:
        e.g. [{'temperature': 300, 'free_energy': float, 'entropy': float, 'heat_capacity': float},
                {'temperature': 310, 'free_energy': float, 'entropy': float, 'heat_capacity': float}, ...]
        """
        if force_rerun or not hasattr(self, '_thermal_properties'):
            print("Calculating phonopy thermal properties...")
            self.phonon.run_thermal_properties(**(phonopy_tprops_kwargs or {}))
            
            tp = self.phonon.get_thermal_properties_dict()
            if tp is not None:
                parsed_data = []

                temperatures = tp["temperatures"]
                free_energies = tp["free_energy"]
                entropies = tp["entropy"]
                heat_capacities = tp["heat_capacity"]

                for i, T in enumerate(temperatures):
                    data_point = {
                        "temperature": T,
                        "free_energy": free_energies[i],
                        "entropy": entropies[i],
                        "heat_capacity": heat_capacities[i],
                    }
                    parsed_data.append(data_point)

                self._thermal_properties = parsed_data
            else:
                print("Thermal properties could not be calculated.")
                return None
        
        return self._thermal_properties

    def summary(
        self,
        calc_dir: str = None,
        savename: str = "phonons.json",
        remake: bool = False,
        include_mesh: bool = False,
        include_force_constants: bool= False,
        include_band_structure = True,
        include_total_dos: bool = True,
        include_thermal_properties: bool = True,
        temperatures = np.linspace(0, 2000, 101),
        band_structure_kwargs: dict | None = None,
        include_phonopy_thermal_properties: bool = False,
        phonopy_tprops_kwargs: dict | None = None,
    ):
        """
        Returns all desired data for post-processing DFT calculations

        Args:
            calc_dir: 
                directory to save calculation results to. If None is provided, will not write.
            include_mesh (bool, optional):  
                Include mesh data in the output. Default is False because mesh data can be quite large.
            include_force_constants (bool, optional):
                Include force constants in the output. Default is True.
            include_band_structure (bool, optional):
                Include band structure in the output. Default is True.
                Remember, if want to set a custom path - need to give band_structure_kwargs
            include_total_dos (bool, optional):         
                Include total density of states in the output. Default is True.
            include_thermal_properties (bool, optional):
                Include thermal properties (F, S, Cv) in the output. Default is True.
            temperatures (list, array):
                Specify a range of temperatures for thermal properties, default is 0-2000.
            band_structure_kwargs (dict, optional): 
               Additional arguments for band structure calculation. See
               `self.band_structure` for details.
            include_phonopy_thermal_properties (bool, optional):
                If True, includes the thermal properties calculated using phonopy's built in functions in the output. Default is False.
                Note that these are in Phonopy's default units (usually THz for frequencies and eV/*primitive* cell for energies)
            phonopy_tprops_kwargs (dict):
                Additional arguments for phonopy thermal properties calculation. See
                `self.phonopy_thermal_properties` for details.

        Returns:
            Dictionary with the specified information
            {'force_constants': array of force constants, 'thermal_properties': dictionary of thermal properties, ....}

        """
        if calc_dir is not None:
            fjson = os.path.join(calc_dir, savename)
            if os.path.exists(fjson) and not remake:
                return read_json(fjson)
        
        data = {}
    
        if include_force_constants:
            fc = self.force_constants
            data["force_constants"] = fc

        if include_mesh:
            mesh_array = self.mesh_dict
            data["mesh"] = mesh_array

        if include_band_structure:
            band_struc = self.band_structure(**(band_structure_kwargs or {}))
            data["band_structure"] = band_struc

        if include_total_dos:
            total_dos = self.total_dos
            data["total_dos"] = total_dos

        if include_thermal_properties:
            helmholtz = self.thermal_properties(temperatures=temperatures,include_heat_capacity=True)
            data["thermal_properties"] = helmholtz

        if include_phonopy_thermal_properties:
            force_rerun = True if phonopy_tprops_kwargs else False
            tp = self.phonopy_thermal_properties(phonopy_tprops_kwargs, force_rerun=force_rerun)
            data["phonopy_thermal_properties"] = tp

        data = convert_numpy_to_native(data)  # Convert to JSON serializable format

        if calc_dir is not None:
            write_json(data, fjson)
            return read_json(fjson)
        else:
            return data

